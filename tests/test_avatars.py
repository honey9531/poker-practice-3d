"""The opponents' 3D characters (assets/avatars) and their import tool."""

import re
import sys

import pytest
from PySide6.QtCore import QUrl
from PySide6.QtQml import QQmlComponent, QQmlEngine

from services.game_session import OPPONENT_NAMES
from services.paths import assets_dir

sys.path.insert(0, str(assets_dir().parent / "tools"))
import import_avatars  # noqa: E402

AVATARS_DIR = assets_dir() / "avatars"


def test_every_opponent_has_a_character():
    assert tuple(import_avatars.AVATARS) == OPPONENT_NAMES
    for name in OPPONENT_NAMES:
        assert (AVATARS_DIR / name / f"Avatar{name}.qml").is_file(), name


@pytest.mark.parametrize("name", OPPONENT_NAMES)
def test_character_files_are_complete(name):
    folder = AVATARS_DIR / name
    text = (folder / f"Avatar{name}.qml").read_text(encoding="utf-8")
    referenced = re.findall(r'source: "((?:meshes|maps)/[^"]+)"', text)
    assert any(path.startswith("meshes/") for path in referenced)
    assert any(path.startswith("maps/") for path in referenced)
    for path in referenced:
        assert (folder / path).is_file(), path
    # Every bone the table poses has an alias.
    for prop in ("pelvis", "spine", "head", "leftUpperArm", "leftForearm", "leftHand", "leftFinger",
                 "rightUpperArm", "rightForearm", "rightHand", "rightFinger",
                 "leftThigh", "leftCalf", "leftFoot", "rightThigh", "rightCalf", "rightFoot"):
        assert f"property alias {prop}:" in text, prop
    # Shipped textures are small.
    for image in (folder / "maps").iterdir():
        assert image.stat().st_size < 400_000, image.name


def test_licence_notice_ships_with_the_characters():
    notice = (AVATARS_DIR / "LICENSE.md").read_text(encoding="utf-8")
    assert "MIT License" in notice and "Copyright (c) 2020 Microsoft" in notice
    assert import_avatars.COMMIT in notice
    for name, avatar in import_avatars.AVATARS.items():
        assert f"| {name} | {avatar} |" in notice


@pytest.mark.parametrize("name", OPPONENT_NAMES)
def test_character_component_loads(qapp, name):
    engine = QQmlEngine()
    component = QQmlComponent(engine, QUrl.fromLocalFile(str(AVATARS_DIR / name / f"Avatar{name}.qml")))
    assert component.isReady(), component.errorString()
    avatar = component.create()
    assert avatar is not None, component.errorString()
    meta = avatar.metaObject()
    assert meta.indexOfProperty("leftHand") >= 0 and meta.indexOfProperty("head") >= 0
    avatar.deleteLater()


SAMPLE = """import QtQuick
import QtQuick3D

Node {
    id: root
    objectName: "Root"

    // Resources
    Texture {
        id: some_texture
        objectName: "c:\\\\temp\\\\x_body_color.tga"
    }
    PrincipledMaterial {
        id: x_body_material
        objectName: "x_body"
        baseColor: "#ff000000"
        baseColorMap: some_texture
    }
    PrincipledMaterial {
        id: x_head_material
        objectName: "x_head"
        baseColor: "#ff000000"
    }
    Node {
        id: bip01_Pelvis
        Node {
            id: bip01_Head
        }
    }
}
"""


def test_rewrite_replaces_materials_and_adds_aliases_for_present_bones():
    textures = {"body_color": "maps/body_color.jpg", "body_normal": "maps/body_normal.jpg",
                "head_color": "maps/head_color.jpg", "head_normal": "maps/head_normal.jpg"}
    out = import_avatars.rewrite_qml(SAMPLE, textures)
    assert "Texture {\n        id: some_texture" not in out and "#ff000000" not in out
    assert 'source: "maps/body_color.jpg"' in out and 'source: "maps/head_normal.jpg"' in out
    assert "id: x_body_material" in out and "id: x_head_material" in out
    assert "property alias pelvis: bip01_Pelvis" in out
    assert "property alias head: bip01_Head" in out
    assert "property alias leftHand" not in out  # not in this skeleton
    assert out.startswith("// Generated by tools/import_avatars.py")
